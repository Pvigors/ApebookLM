export function getHelpCategory(slug: string): HelpCategory | undefined {
  return HELP_CATEGORIES.find((c) => c.slug === slug);
}

/** 文章页所需:分类、文章、同分类内的上一篇/下一篇。 */
export function getArticleNav(catSlug: string, artSlug: string): {
  category: HelpCategory;
  article: HelpArticle;
  prev: HelpArticle | null;
  next: HelpArticle | null;
} | null {
  const category = getHelpCategory(catSlug);
  if (!category) return null;
  const i = category.articles.findIndex((a) => a.slug === artSlug);
  if (i < 0) return null;
  return {
    category,
    article: category.articles[i],
    prev: i > 0 ? category.articles[i - 1] : null,
    next: i < category.articles.length - 1 ? category.articles[i + 1] : null,
  };
}
